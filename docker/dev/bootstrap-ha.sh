#!/usr/bin/env bash
# Starts the dev Home Assistant (compose.dev.yaml) and makes it usable by the engine in standalone mode:
# creates a local test user through the onboarding API and a long-lived access token.
#
# Idempotent: when docker/dev/.env.dev already holds a token that Home Assistant accepts, nothing changes.
# The generated credentials and the token live in docker/dev/.env.dev only (git-ignored, mode 0600):
#   HA_URL, HA_TOKEN             -> read by the engine in standalone mode (export them or `set -a; . docker/dev/.env.dev`)
#   HA_DEV_USER, HA_DEV_PASSWORD -> the local test user, to log into the Home Assistant UI
#
# Needs only Docker (node:22 runs the onboarding script, with the host network to reach localhost:8123).
set -euo pipefail

DEV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${DEV_DIR}/../.." && pwd)"
ENV_FILE="${DEV_DIR}/.env.dev"
NODE_IMAGE="node:22.12.0-alpine"

docker compose -f "${ROOT_DIR}/compose.dev.yaml" up -d

if [[ -f "${ENV_FILE}" ]]; then
    # shellcheck disable=SC1090
    set -a && source "${ENV_FILE}" && set +a
fi
HA_URL="${HA_URL:-http://localhost:8123}"

if [[ -n "${HA_TOKEN:-}" ]]; then
    # Home Assistant may still be starting: wait for it to answer before judging the token.
    for _ in $(seq 1 90); do
        status="$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer ${HA_TOKEN}" "${HA_URL}/api/" || true)"
        [[ "${status}" == "200" || "${status}" == "401" ]] && break
        sleep 2
    done
    if [[ "${status:-}" == "200" ]]; then
        echo "Already bootstrapped: ${ENV_FILE} holds a working token."
        exit 0
    fi
    echo "The stored token is not accepted (HTTP ${status:-none}); logging in again."
fi

if [[ -z "${HA_DEV_USER:-}" || -z "${HA_DEV_PASSWORD:-}" ]]; then
    HA_DEV_USER="devclimate"
    HA_DEV_PASSWORD="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)"
fi

token="$(docker run --rm --network host \
    -e HA_URL="${HA_URL}" -e HA_DEV_USER="${HA_DEV_USER}" -e HA_DEV_PASSWORD="${HA_DEV_PASSWORD}" \
    -v "${DEV_DIR}/bootstrap-ha.mjs:/bootstrap-ha.mjs:ro" \
    "${NODE_IMAGE}" node /bootstrap-ha.mjs | tail -n 1)"

if [[ -z "${token}" ]]; then
    echo "No token was produced." >&2
    exit 1
fi

umask 077
cat > "${ENV_FILE}" <<EOF
# Generated by docker/dev/bootstrap-ha.sh: local development secrets, never commit.
HA_URL=${HA_URL}
HA_TOKEN=${token}
HA_DEV_USER=${HA_DEV_USER}
HA_DEV_PASSWORD=${HA_DEV_PASSWORD}
EOF
chmod 600 "${ENV_FILE}"
echo "Home Assistant is ready at ${HA_URL}; credentials and token saved in ${ENV_FILE}."
